# Determine applicability
def is_applicable(m):
    """Check if matrix item applies to this contract profile"""
    pf = m.get('only_for_product', 'common')
    lf = m.get('only_for_lot', 'common')
    tf = m.get('only_for_terminal', 'common')
    pm = m.get('payment_method', 'common')
    
    # Product filter
    if pf == 'internet_acquiring' and 'internet_acquiring' not in profile['product']:
        return False, 'out_of_scope', 'Internet acquiring not in contract scope'
    if pf == 'trade_acquiring' and 'trade_acquiring' not in profile['product']:
        return False, 'out_of_scope', 'Trade acquiring not in contract scope'
    
    # Lot filter
    if lf == 'fz_223' and profile['lot'] != 'fz_223':
        return False, 'not_applicable', 'Contract is 44-FZ, not 223-FZ'
    if lf == 'fz_44' and profile['lot'] != 'fz_44':
        return False, 'not_applicable', 'Contract is not 44-FZ'
    
    # Terminal filter
    if tf == 'smart' and 'smart' not in profile['terminal']:
        return False, 'not_applicable', 'Smart terminals not in contract scope'
    if tf == 'pos' and 'pos' not in profile['terminal']:
        return False, 'not_applicable', 'POS terminals not in contract scope'
    
    # Payment method filter
    if pm == 'sber_pay_face_scan':
        return False, 'out_of_scope', 'SberPay FaceScan not in contract scope'
    if pm == 'sber_pay' and 'sber_pay' not in profile.get('payment_method', []):
        return False, 'out_of_scope', 'SberPay not in contract scope'
    if pm == 'qr_sber_pay':
        return False, 'out_of_scope', 'SberPay QR not in contract scope'
    
    return True, 'applicable', ''

